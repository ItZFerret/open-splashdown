#!/usr/bin/env python3
"""The VU microcode upload packets for the PC port.

The retail region 0x3E0000-0x3F8E00 is a chain of DMA tags (REF, CNT, END)
whose data are VIF MPG codes uploading VU0/VU1 microprograms; seven more
(CNT tags with the code inline) sit at 0x3DB000 in .text. `make link`
writes them as build/link/vupackets.s and a chunk_*.s (spimdisasm syntax).

usage:
  tools/port/vu.py gen OUT.s [elf|macho|coff]
                                   the region as assembly for x86-64 (same
                                   bytes). Without `make link`'s output, or
                                   for Mach-O and COFF, it is read from the
                                   game's executable in baserom/ instead
                                   (its symbol table names the programs)
  tools/port/vu.py dis [NAME ...]  disassemble the named microprograms (all
                                   if none), at their VU micro-memory
                                   addresses
  tools/port/vu.py list            each program: its MPG load addresses
"""
import glob
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "build/link/vupackets.s")


def sources():
    """build/link/vupackets.s and the .text chunk holding the rest of the
    microcode (Vu0MiscCode ... ProjectedStripRendererCode: CNT tags)."""
    if not os.path.exists(SRC):
        sys.exit(f"vu.py: {os.path.relpath(SRC, ROOT)} is missing: run `make link` first")
    out = [SRC]
    for path in sorted(glob.glob(os.path.join(ROOT, "build/link/chunk_*.s"))):
        with open(path) as f:
            if "\nVu0MiscCode:\n" in f.read():
                out.append(path)
    return out

LINE = re.compile(r"/\* [0-9A-F]+ ([0-9A-F]{8}) [0-9A-F]{8} \*/ \.word (\S+)")


def parse(paths=None):
    words = {}     # address -> int or label
    labels = {}    # name -> address
    order = []     # (kind, value) in file order
    pending = []
    for line in (l for path in (paths or sources()) for l in open(path)):
        s = line.strip()
        m = LINE.search(s)
        if m:
            addr = int(m.group(1), 16)
            v = m.group(2)
            for name in pending:
                labels[name] = addr
                order.append(("label", name))
            pending = []
            words[addr] = int(v, 16) if v.startswith("0x") else v
            order.append(("word", addr))
        elif s.startswith("dlabel "):
            pending.append(s.split()[1])
        elif s.endswith(":") and not s.startswith("."):
            pending.append(s[:-1])
    for name in pending:
        labels[name] = max(words) + 4
        order.append(("label", name))
    return words, labels, order


def word(words, labels, a):
    v = words.get(a, 0)
    return labels[v] if isinstance(v, str) else v


def globals_(paths=None):
    return [l.split()[1] for path in (paths or sources()) for l in open(path) if l.startswith(".global ")]


def gen_link(out):
    lines = ["# Generated by tools/port/vu.py from build/link/vupackets.s and the",
             "# .text chunk with the rest of the microcode: retail's VU microcode",
             "# upload packets, byte for byte, REF tags' addresses as labels.",
             ".section .data.vupackets, \"aw\"", ".balign 128", "port_vupackets_start:"]
    for n, path in enumerate(sources()):
        words, labels, order = parse([path])
        g = set(globals_([path]))
        # REF tags whose address is a number (the .text chunk's: spimdisasm
        # doesn't symbolize them) point into this file: label + offset
        base_name, base = f"port_vu_base{n}", min(words)
        for name in g:
            a = labels.get(name)
            for _ in range(64):
                if a is None or not isinstance(words.get(a, 0), int):
                    break
                t0 = words[a]
                tid, qwc = (t0 >> 28) & 7, t0 & 0xFFFF
                if tid == 3 and isinstance(words.get(a + 4), int) and words[a + 4] in words:
                    words[a + 4] = f"{base_name} + {words[a + 4] - base:#x}"
                if tid == 1:
                    a += 16 + qwc * 16
                elif tid == 3:
                    a += 16
                else:
                    break
        lines.append(".balign 128")
        lines.append(f"{base_name}:")
        prev = None
        for kind, v in order:
            if kind == "label":
                if v in g:
                    lines.append(f".globl {v}")
                lines.append(f"{v}:")
            else:
                if prev is not None and v != prev + 4:
                    lines.append(f"    .zero {v - prev - 4}")
                prev = v
                w = words[v]
                lines.append(f"    .long {w}" if isinstance(w, str) else f"    .long {w:#010x}")
    # no run-time relocations: the assembler resolved the REF tags
    lines += ["port_vupackets_end:", ".globl port_vupackets_start", ".globl port_vupackets_end",
              "port_vurelocs:", "port_vurelocs_end:", ".globl port_vurelocs", ".globl port_vurelocs_end",
              ".section .note.GNU-stack,\"\",@progbits"]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w").write(text)



def elf_path():
    """The game's executable, for the microcode when `make link` hasn't run:
    $SPLASHDOWN_ELF, else the first of baserom/SLUS_202.23 (NTSC-U),
    baserom/SLES_504.86 (PAL), any other baserom/S???_???.??."""
    env = os.environ.get("SPLASHDOWN_ELF")
    if env:
        return env
    for name in ("SLUS_202.23", "SLES_504.86"):
        path = os.path.join(ROOT, "baserom", name)
        if os.path.exists(path):
            return path
    found = sorted(glob.glob(os.path.join(ROOT, "baserom/S[A-Z][A-Z][A-Z]_[0-9][0-9][0-9].[0-9][0-9]")))
    return found[0] if found else None


def program_names():
    """The microprograms the port links against (ports/pc/sdk/microcode.cpp)."""
    text = open(os.path.join(ROOT, "ports/pc/sdk/microcode.cpp")).read()
    return [n for n in re.findall(r"^extern char (\w+)\[\];", text, re.M) if not n.startswith("port_")]


class Elf:
    """A 32-bit little-endian ELF with its symbol table (retail keeps it)."""

    # The NTSC-U executable's section header table is cut short (the file
    # ends in it), so its symbol and string tables are found by their
    # offsets (tools/extract_symbols.py), for that exact file.
    KNOWN = {"496ba6a5bfe9d7e68ea2edb993b493033ccc9bae": (0x29EB50, 18162, 0x24EB60)}

    def __init__(self, path):
        self.data = d = open(path, "rb").read()
        if d[:6] != b"\x7fELF\x01\x01":
            sys.exit(f"vu.py: {path} is not a 32-bit little-endian ELF")
        phoff, shoff = struct.unpack_from("<II", d, 0x1C)
        phentsize, phnum, shentsize, shnum = struct.unpack_from("<HHHH", d, 0x2A)
        # (vaddr, file offset, file size) of each loaded segment
        self.loads = []
        for i in range(phnum):
            ptype, off, vaddr, _, filesz = struct.unpack_from("<5I", d, phoff + i * phentsize)
            if ptype == 1:
                self.loads.append((vaddr, off, filesz))
        sections = [struct.unpack_from("<10I", d, shoff + i * shentsize) for i in range(shnum)
                    if shoff + i * shentsize + 40 <= len(d)]
        tables = [(sh[4], sh[5] // 16, sections[sh[6]][4]) for sh in sections
                  if sh[1] == 2 and sh[6] < len(sections) and sections[sh[6]][1] == 3]
        if not tables:
            import hashlib
            known = self.KNOWN.get(hashlib.sha1(d).hexdigest())
            if not known:
                sys.exit(f"vu.py: {path} has no symbol table the section headers lead to")
            tables = [known]
        self.symbols = {}
        for symoff, count, stroff in tables:
            for off in range(symoff, symoff + count * 16, 16):
                name, value, size, info, other, shndx = struct.unpack_from("<IIIBBH", d, off)
                if not shndx or info & 15 > 2:
                    continue
                end = d.find(b"\0", stroff + name)
                if end < 0:
                    continue
                text = d[stroff + name:end].decode("latin-1")
                # a global over a local of the same name
                if text and (info >> 4 or text not in self.symbols):
                    self.symbols[text] = value

    def word(self, addr):
        for vaddr, off, filesz in self.loads:
            if vaddr <= addr < vaddr + filesz:
                return struct.unpack_from("<I", self.data, off + addr - vaddr)[0]
        sys.exit(f"vu.py: address {addr:#x} is not in the executable's loaded segments")


def gen_elf(out, fmt, path):
    """The upload packets straight from the executable: one block of its
    bytes from the first microprogram's chain to the last one's data, the
    chains' names as labels. A REF tag's address can't be a 32-bit
    relocation in Mach-O or 64-bit COFF, so the tags keep retail's and a
    table (tag offset, target offset) lets ports/pc/sdk/microcode.cpp point
    them at the block before the game runs."""
    elf = Elf(path)
    names = program_names()
    missing = [n for n in names if n not in elf.symbols]
    if missing:
        sys.exit(f"vu.py: {path} has no symbol {', '.join(missing)}")
    lo, hi, relocs = None, 0, {}
    for name in names:
        a = elf.symbols[name]
        for _ in range(64):
            t0, t1 = elf.word(a), elf.word(a + 4)
            tid, qwc = (t0 >> 28) & 7, t0 & 0xFFFF
            spans = [(a, a + 16)]
            if tid == 1:        # cnt: the data follows the tag
                spans.append((a + 16, a + 16 + qwc * 16))
                nxt = a + 16 + qwc * 16
            elif tid == 3:      # ref: the data is elsewhere
                spans.append((t1, t1 + qwc * 16))
                relocs[a + 4] = t1
                nxt = a + 16
            elif tid == 7:      # end
                spans.append((a + 16, a + 16 + qwc * 16))
                nxt = None
            else:
                sys.exit(f"vu.py: {name}: tag {t0:#x} at {a:#x}")
            for s, e in spans:
                lo = s if lo is None else min(lo, s)
                hi = max(hi, e)
            if nxt is None:
                break
            a = nxt
    lo &= ~127
    hi = (hi + 15) & ~15
    us = "_" if fmt == "macho" else ""
    section = {"elf": '.section .data.vupackets, "aw"', "macho": ".data", "coff": ".data"}[fmt]
    labels = {}
    for name in names:
        labels.setdefault(elf.symbols[name], []).append(name)
    lines = [f"# Generated by tools/port/vu.py from {os.path.basename(path)}: retail's VU microcode",
             f"# upload packets, {lo:#x}-{hi:#x}, byte for byte.",
             section, ".balign 128", f".globl {us}port_vupackets_start", f"{us}port_vupackets_start:"]
    for a in range(lo, hi, 4):
        for name in labels.get(a, ()):
            lines += [f".globl {us}{name}", f"{us}{name}:"]
        lines.append(f"    .long {elf.word(a):#010x}")
    lines += [f".globl {us}port_vupackets_end", f"{us}port_vupackets_end:",
              ".balign 8", f".globl {us}port_vurelocs", f"{us}port_vurelocs:"]
    for tag, target in sorted(relocs.items()):
        lines.append(f"    .long {tag - lo:#x}, {target - lo:#x}")
    lines += [f".globl {us}port_vurelocs_end", f"{us}port_vurelocs_end:"]
    if fmt == "elf":
        lines.append('.section .note.GNU-stack,"",@progbits')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w").write(text)


def gen(out, fmt="elf"):
    """`make link`'s output if it is there (ELF hosts), else the executable."""
    if fmt == "elf" and os.path.exists(SRC):
        return gen_link(out)
    path = elf_path()
    if not path or not os.path.exists(path):
        sys.exit("vu.py: no microcode source: copy the game's executable from your disc to baserom/ "
                 "(SLUS_202.23 or SLES_504.86), or set SPLASHDOWN_ELF"
                 + (", or run `make link`" if fmt == "elf" else ""))
    gen_elf(out, fmt, path)


def chain(words, labels, start):
    """Walk the DMA chain at start; yield (vu_addr_dwords, [(lo, hi)...])
    for each MPG."""
    a = start
    mpgs = []
    for _ in range(64):
        t0 = word(words, labels, a)
        t1 = word(words, labels, a + 4)
        qwc = t0 & 0xFFFF
        tid = (t0 >> 28) & 7
        if tid == 1:      # cnt
            data, nxt = a + 16, a + 16 + qwc * 16
        elif tid == 3:    # ref
            data, nxt = t1, a + 16
        elif tid == 7:    # end
            data, nxt = a + 16, None
        else:
            raise SystemExit(f"tag {t0:#x} at {a:#x}")
        # VIF1 DMA runs with TTE set: the tag's upper 64 bits go to the VIF
        # before its data.
        stream = [a + 8, a + 12] + list(range(data, data + qwc * 16, 4))
        k = 0
        while k < len(stream):
            code = word(words, labels, stream[k])
            cmd = (code >> 24) & 0x7F
            k += 1
            if cmd == 0x4A:
                num = (code >> 16) & 0xFF or 256
                addr = code & 0xFFFF
                instrs = []
                for i in range(num):
                    instrs.append((word(words, labels, stream[k]), word(words, labels, stream[k + 1])))
                    k += 2
                mpgs.append((addr, instrs))
            elif cmd in (0, 0x10, 0x11, 0x13):
                pass
            else:
                raise SystemExit(f"VIF code {code:#x} at {stream[k - 1]:#x}")
        if nxt is None:
            return mpgs
        a = nxt
    return mpgs


F = "xyzw"


def dest(d):
    return "".join(c for i, c in enumerate(F) if d & (8 >> i))


def upper(w):
    flags = "".join(f for b, f in ((31, "[I]"), (30, "[E]"), (29, "[M]"), (28, "[D]"), (27, "[T]")) if w >> b & 1)
    d = dest(w >> 21 & 15)
    ft, fs, fd = w >> 16 & 31, w >> 11 & 31, w >> 6 & 31
    op = w & 63
    bc = F[w & 3]
    names = {0: "add", 1: "sub", 2: "madd", 3: "msub", 4: "max", 5: "mini", 6: "mul"}
    if op < 0x1C:
        return f"{names[op >> 2]}{bc}.{d} vf{fd}, vf{fs}, vf{ft}{bc}" + flags
    t = {0x1C: "mulq", 0x1D: "maxi", 0x1E: "muli", 0x1F: "minii", 0x20: "addq", 0x21: "maddq", 0x22: "addi",
         0x23: "maddi", 0x24: "subq", 0x25: "msubq", 0x26: "subi", 0x27: "msubi"}
    if op in t:
        return f"{t[op]}.{d} vf{fd}, vf{fs}, {t[op][-1]}" + flags
    t = {0x28: "add", 0x29: "madd", 0x2A: "mul", 0x2B: "max", 0x2C: "sub", 0x2D: "msub", 0x2E: "opmsub", 0x2F: "mini"}
    if op in t:
        return f"{t[op]}.{d} vf{fd}, vf{fs}, vf{ft}" + flags
    if op >= 0x3C:
        s = ((w >> 6 & 31) << 2) | (w & 3)
        if s < 0x10:
            return f"{['adda', 'suba', 'madda', 'msuba'][s >> 2]}{F[s & 3]}.{d} ACC, vf{fs}, vf{ft}{F[s & 3]}" + flags
        if s < 0x18:
            return f"{['itof0', 'itof4', 'itof12', 'itof15', 'ftoi0', 'ftoi4', 'ftoi12', 'ftoi15'][s - 0x10]}.{d} vf{ft}, vf{fs}" + flags
        if s < 0x1C:
            return f"mula{F[s & 3]}.{d} ACC, vf{fs}, vf{ft}{F[s & 3]}" + flags
        t = {0x1C: "mulaq", 0x1E: "mulai", 0x20: "addaq", 0x21: "maddaq", 0x22: "addai", 0x23: "maddai",
             0x24: "subaq", 0x25: "msubaq", 0x26: "subai", 0x27: "msubai"}
        if s in t:
            return f"{t[s]}.{d} ACC, vf{fs}, {t[s][-1]}" + flags
        if s == 0x1D:
            return f"abs.{d} vf{ft}, vf{fs}" + flags
        if s == 0x1F:
            return f"clipw.xyz vf{fs}, vf{ft}w" + flags
        t = {0x28: "adda", 0x29: "madda", 0x2A: "mula", 0x2C: "suba", 0x2D: "msuba", 0x2E: "opmula"}
        if s in t:
            return f"{t[s]}.{d} ACC, vf{fs}, vf{ft}" + flags
        if s == 0x2F:
            return "nop" + flags
    return f"upper? {w:#010x}" + flags


def sx(v, bits):
    return v - (1 << bits) if v & (1 << (bits - 1)) else v


