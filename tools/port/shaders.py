#!/usr/bin/env python3
"""Compile the GPU renderer's Vulkan shaders (ports/pc/shaders) into
ports/pc/gpu_spirv.h, which is checked in so that building the port doesn't
need a shader compiler. Run it after changing a shader; it needs
glslangValidator (the Vulkan SDK, or the glslang package).
"""
import pathlib
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "ports/pc/shaders"
OUT = ROOT / "ports/pc/gpu_spirv.h"

# name in the header, source, stage, defines
SHADERS = [
    ("kSpirvVert", "gpu.vert", "vert", []),
    ("kSpirvFrag", "gpu.frag", "frag", []),
    ("kSpirvFragZ", "gpu.frag", "frag", ["EXACTZ"]),
]


def compile_one(source, stage, defines):
    with tempfile.TemporaryDirectory() as tmp:
        spv = pathlib.Path(tmp) / "out.spv"
        cmd = ["glslangValidator", "-V", "-S", stage, "-o", str(spv)]
        cmd += ["-D" + d for d in defines]
        cmd.append(str(SRC / source))
        done = subprocess.run(cmd, capture_output=True, text=True)
        if done.returncode != 0:
            sys.exit(done.stdout + done.stderr)
        return spv.read_bytes()


def main():
    lines = [
        "// Generated by tools/port/shaders.py from ports/pc/shaders: don't edit.",
        "#ifndef PORT_GPU_SPIRV_H",
        "#define PORT_GPU_SPIRV_H",
        "",
        "#include <cstdint>",
        "",
    ]
    for name, source, stage, defines in SHADERS:
        code = compile_one(source, stage, defines)
        words = struct.unpack("<%dI" % (len(code) // 4), code)
        what = source + (" with " + ", ".join(defines) if defines else "")
        lines.append("// %s" % what)
        lines.append("static const uint32_t %s[] = {" % name)
        for i in range(0, len(words), 8):
            lines.append("    " + " ".join("0x%08x," % w for w in words[i:i + 8]))
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
